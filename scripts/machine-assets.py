#!/usr/bin/env python3
"""Publish and lock reviewed Pi machine artifacts. No registry credentials in outputs."""
import argparse
import hashlib
import json
from pathlib import Path
import re
import subprocess

ROOT = Path(__file__).resolve().parents[1]
MACHINE = 'raspberry-pi-3'
COMPONENTS = ('linux-kernel', 'u-boot', 'firmware', 'ostree-initramfs')
LOCK = 'machine-assets.lock.json'
OVERLAY = 'hosted-machine-assets.hcl'


def run(args, capture=False):
    return subprocess.run(args, cwd=ROOT, check=True, text=True,
                          stdout=subprocess.PIPE if capture else None).stdout


def bake():
    return ['docker', 'buildx', 'bake', '-f', 'docker-bake.hcl',
            '-f', 'machines/' + MACHINE + '.hcl']


def fingerprint():
    # Hash effective component recipes, not the rootfs, agent or user profile.
    plan = json.loads(run(bake() + ['--print', *COMPONENTS], capture=True))['target']
    recipes = {name: {key: value for key, value in plan[name].items()
                     if key in ('context', 'dockerfile', 'args', 'contexts', 'platforms')}
               for name in ('nulix-builder', *COMPONENTS)}
    files = {}
    for directory in ('builder', *(f'recipes/{name}' for name in COMPONENTS)):
        for file in sorted((ROOT / directory).rglob('*')):
            if file.is_symlink():
                raise ValueError('Machine recipes must not contain symlinks: ' + str(file))
            if file.is_file():
                files[file.relative_to(ROOT).as_posix()] = hashlib.sha256(file.read_bytes()).hexdigest()
    return hashlib.sha256(json.dumps({'recipes': recipes, 'files': files}, sort_keys=True).encode()).hexdigest()


def overlay(lock):
    components = lock.get('components', {})
    if lock.get('schemaVersion') != 1 or lock.get('machine') != MACHINE or set(components) != set(COMPONENTS):
        raise ValueError('Invalid machine asset lock')
    for name, ref in components.items():
        if not isinstance(ref, str) or not re.fullmatch(
                r'ghcr\.io/[a-z0-9][a-z0-9._/-]+@sha256:[a-f0-9]{64}', ref):
            raise ValueError('Component must use a GHCR sha256 digest: ' + name)
    lines = ['# Generated by scripts/machine-assets.py; commit with machine-assets.lock.json.',
             'group "default" {', '  targets = ["ostree-rootfs", "ostree-sd-image"]', '}']
    for target, names in [('ostree-rootfs', ('linux-kernel', 'ostree-initramfs')),
                          ('ostree-sd-image', ('linux-kernel', 'u-boot', 'firmware'))]:
        lines += ['', f'target "{target}" {{', '  contexts = {']
        lines += [f'    {name} = "docker-image://{components[name]}"' for name in names]
        lines += ['  }', '}']
    return '\n'.join(lines) + '\n'


def check():
    lock = json.loads((ROOT / LOCK).read_text())
    if lock.get('inputsSha256') != fingerprint():
        raise ValueError('Machine recipes changed. Publish new foundation assets before building.')
    if (ROOT / OVERLAY).read_text() != overlay(lock):
        raise ValueError('Machine asset overlay does not match the digest lock.')
    plan = json.loads(run(bake() + ['-f', OVERLAY, '--print'], capture=True))
    if set(plan['group']['default']['targets']) != {'ostree-rootfs', 'ostree-sd-image'} or any(name in plan['target'] for name in COMPONENTS):
        raise ValueError('Pinned builds must not compile machine components.')
    print('Verified pinned machine artifacts for ' + MACHINE)


def publish(repository):
    repository = repository.lower()
    if not re.fullmatch(r'[a-z0-9][a-z0-9-]*/[a-z0-9][a-z0-9._-]*', repository):
        raise ValueError('Expected GitHub owner/repository')
    inputs = fingerprint()
    revision = run(['git', 'rev-parse', 'HEAD'], capture=True).strip()
    output = ROOT / 'out' / 'machine-assets'
    output.mkdir(parents=True, exist_ok=True)
    components = {}
    # Sequential publication avoids four compilers competing for one runner.
    for component in COMPONENTS:
        image = f'ghcr.io/{repository}/{MACHINE}-{component}'
        metadata = output / (component + '.json')
        run(bake() + [component,
            '--set', component + '.output=type=image,push=true',
            '--set', component + '.tags=' + image + ':' + inputs,
            '--set', component + '.labels.org.opencontainers.image.source=https://github.com/' + repository,
            '--set', component + '.labels.org.opencontainers.image.revision=' + revision,
            '--set', component + '.cache-from=type=registry,ref=' + image + ':buildcache',
            '--set', component + '.cache-to=type=registry,ref=' + image + ':buildcache,mode=max',
            '--provenance=false', '--metadata-file', str(metadata)])
        digest = json.loads(metadata.read_text())[component]['containerimage.digest']
        if not re.fullmatch(r'sha256:[a-f0-9]{64}', digest):
            raise ValueError('BuildKit returned an invalid image digest')
        components[component] = image + '@' + digest
    lock = {'schemaVersion': 1, 'machine': MACHINE, 'sourceCommit': revision,
            'inputsSha256': inputs, 'components': components}
    # Only replace the lock once every publication succeeds.
    (ROOT / LOCK).write_text(json.dumps(lock, indent=2) + '\n')
    (ROOT / OVERLAY).write_text(overlay(lock))
    check()


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('command', choices=('publish', 'check'))
    parser.add_argument('--repository', default='nulix/nulix-alpine')
    args = parser.parse_args()
    try:
        publish(args.repository) if args.command == 'publish' else check()
    except (ValueError, KeyError, OSError, subprocess.CalledProcessError) as error:
        parser.exit(1, 'Machine assets: ' + str(error) + '\n')
